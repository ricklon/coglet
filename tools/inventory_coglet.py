"""Inventory the pinned upstream Bambu 3MF without changing its geometry.

Names come from slicer metadata. Bounds are mesh-local, not assembly dimensions.
Only explicitly named archive entries are read/written; no bulk ZIP extraction.
"""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
CAD = ROOT / 'hardware/mechanical'
SOURCE = CAD / 'original/CogletC0_6_8.3mf'
OUT = CAD / 'reference'


def metadata(element):
    return {m.get('key'): m.get('value') for m in element.findall('metadata')
            if m.get('key')}


def main():
    manifest = json.loads((CAD / 'original/manifest.json').read_text())
    expected = next(f['sha256'] for f in manifest['files'] if f['file'] == SOURCE.name)
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != expected:
        raise ValueError('Source differs from pinned manifest')
    OUT.mkdir(parents=True, exist_ok=True)
    rows, plates = [], []
    with ZipFile(SOURCE) as archive:
        settings = ET.fromstring(archive.read('Metadata/model_settings.config'))
        model = ET.fromstring(archive.read('3D/3dmodel.model'))
        if model.get('unit') != 'millimeter':
            raise ValueError('Expected millimeter model')
        objects = {o.get('id'): o for o in model.findall('{*}resources/{*}object')}
        placements = {}
        for plate in settings.findall('plate'):
            info = metadata(plate)
            number = int(info['plater_id'])
            members = [metadata(i)['object_id'] for i in plate.findall('model_instance')]
            for member in members:
                if member in placements:
                    raise ValueError('Repeated object placement needs explicit instance handling')
                placements[member] = number
            preview = f'plate-{number}.png'
            (OUT / preview).write_bytes(archive.read(f'Metadata/plate_{number}.png'))
            plates.append({'plate': number, 'name': info.get('plater_name') or 'Unnamed upstream plate',
                           'objects': members, 'preview': preview})
        models = {}
        for obj in settings.findall('object'):
            oid = obj.get('id')
            parts = {p.get('id'): metadata(p) for p in obj.findall('part')}
            for component in objects[oid].findall('{*}components/{*}component'):
                path = next(v for k, v in component.attrib.items() if k.endswith('}path')).lstrip('/')
                if path not in models:
                    r = ET.fromstring(archive.read(path))
                    if r.get('unit', 'millimeter') != 'millimeter':
                        raise ValueError('Unexpected component units')
                    models[path] = {o.get('id'): o for o in r.findall('{*}resources/{*}object')}
                pid = component.get('objectid')
                mesh = models[path][pid].find('{*}mesh')
                vertices = [tuple(float(v.get(k)) for k in ('x', 'y', 'z'))
                            for v in mesh.findall('{*}vertices/{*}vertex')]
                triangles = mesh.findall('{*}triangles/{*}triangle')
                for tri in triangles:
                    if any(not 0 <= int(tri.get(k)) < len(vertices) for k in ('v1', 'v2', 'v3')):
                        raise ValueError('Invalid triangle index')
                low = [min(v[i] for v in vertices) for i in range(3)]
                high = [max(v[i] for v in vertices) for i in range(3)]
                rows.append({'id': f'C068-O{oid}-P{pid}', 'plate': placements[oid],
                             'name': parts[pid].get('name', 'Unnamed'), 'model_path': path,
                             'object_id': pid, 'vertices': len(vertices), 'triangles': len(triangles),
                             'local_min_mm': low, 'local_max_mm': high,
                             'local_size_mm': [round(b-a, 3) for a, b in zip(low, high)],
                             'component_transform': component.get('transform'),
                             'source_file_hint': parts[pid].get('source_file'),
                             'role': 'Unverified'})
    rows.sort(key=lambda r: (r['plate'], r['id']))
    result = {'source': SOURCE.name, 'source_sha256': expected, 'units': 'mm',
              'coordinate_note': 'Mesh-local bounds; component transforms and build placements are not applied.',
              'plates': plates, 'parts': rows}
    (OUT / 'inventory.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    lines = ['# C0_6_8 print-pack inventory', '',
             'Generated by `python tools/inventory_coglet.py` from the pinned upstream 3MF.', '',
             f'{len(plates)} plates, {len(rows)} component occurrences. These are not a robot BOM:',
             'the pack includes alternative skins and repeated parts. Functional roles are unverified.',
             'Dimensions are mesh-local bounding boxes in mm, not installed clearances.', '',
             'Names and plate previews are upstream material by Will Cogley / NMRobotics LTD;',
             'see [license](../original/LICENSE.upstream) and [provenance](../UPSTREAM.md).', '']
    for plate in plates:
        lines += [f"## Plate {plate['plate']}: {plate['name']}", '',
                  f"![Upstream plate preview]({plate['preview']})", '',
                  '| ID | Upstream name | Local X × Y × Z (mm) | Triangles |',
                  '|---|---|---|---|']
        for row in rows:
            if row['plate'] == plate['plate']:
                size = ' × '.join(f'{v:.2f}' for v in row['local_size_mm'])
                lines.append(f"| {row['id']} | {row['name']} | {size} | {row['triangles']} |")
        lines.append('')
    (OUT / 'INVENTORY.md').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Inventoried {len(rows)} component occurrences across {len(plates)} plates; source hash and triangle indices passed.')


if __name__ == '__main__':
    main()
